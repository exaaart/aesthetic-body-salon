const NBSP = ' ';

/** Короткие предлоги, союзы и местоимения, после которых нельзя переносить строку. */
const SHORT_WORD_RE =
  /(^|[\s(«" ])(а|в|во|и|к|ко|о|об|от|с|со|у|на|не|ни|но|по|за|из|до|для|без|под|над|при|про|что|как|или|же|ли|бы|мы|вы|он|её|их|ваш|наш|я) /giu;

/** Неразрывные пробелы после коротких слов и перед тире. */
export const typo = (text: string): string =>
  text
    // Два прохода: подряд идущие короткие слова («и в салоне») делят между собой пробел.
    .replace(SHORT_WORD_RE, `$1$2${NBSP}`)
    .replace(SHORT_WORD_RE, `$1$2${NBSP}`)
    .replace(/ — /g, `${NBSP}— `)
    .replace(/(\d) (\d)/g, `$1${NBSP}$2`)
    // Число не отрывается от единицы: «70 минут», «2 000 ₽».
    .replace(/(\d) (?=[\p{L}₽])/gu, `$1${NBSP}`);
